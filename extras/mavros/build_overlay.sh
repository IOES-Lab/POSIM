#!/usr/bin/env bash
# Build an isolated MAVROS 2.16.0 overlay; never overwrite /opt/ros.
set -eo pipefail
if [ "$#" -ne 1 ]; then echo "Usage: $0 NEW_WORKSPACE_DIRECTORY" >&2; exit 2; fi
root=$(cd -- "$(dirname -- "$0")" && pwd)
workspace=$1
if [ -e "$workspace" ]; then
  echo "Refusing an existing path: $workspace (choose a new empty location)" >&2; exit 2
fi
# External ROS environment, available on the target host.
# shellcheck source=/dev/null
source /opt/ros/lyrical/setup.bash
for tool in curl tar git colcon sha256sum; do command -v "$tool" >/dev/null; done
python3 - <<'CHECK'
from pathlib import Path
import xml.etree.ElementTree as ET
for package in ('mavros', 'libmavconn', 'mavros_msgs'):
    path = Path('/opt/ros/lyrical/share') / package / 'package.xml'
    version = ET.parse(path).findtext('version')
    if version != '2.16.0':
        raise SystemExit(
            f'This Router backport requires {package} 2.16.0; found {version}. '
            'Review the upstream Router fixes in the official release before '
            'updating or retiring this backport.'
        )
CHECK
mkdir -p "$workspace/src"
workspace=$(cd -- "$workspace" && pwd)
cd "$workspace"
curl --fail --location --connect-timeout 20 --max-time 300 --retry 2 \
  https://codeload.github.com/mavlink/mavros/tar.gz/refs/tags/2.16.0 -o source.tar.gz
printf '%s  %s\n' 47d1f26b484a78b670744734e5c5bb310f29043899ba3ebf9694adb1c8c7bc9b source.tar.gz | sha256sum -c -
tar -xzf source.tar.gz -C src
cd src/mavros-2.16.0
printf '%s  %s\n' \
  138d43eed91da57143c453cdf0c1c1bad852a9a50627349bdc98a9720f962d7e "$root/a974025818cd6101a633c8c059c1a0155132d588.patch" \
  8832e6d396c8532c3fc7060af1eb74780456a2adfc36521fab17520ad1dc1911 "$root/2b788a04e69e0aaaef78b9175f816dfcc565b5a0.patch" | sha256sum -c -
git apply --check "$root/a974025818cd6101a633c8c059c1a0155132d588.patch"
git apply "$root/a974025818cd6101a633c8c059c1a0155132d588.patch"
git apply --check "$root/2b788a04e69e0aaaef78b9175f816dfcc565b5a0.patch"
git apply "$root/2b788a04e69e0aaaef78b9175f816dfcc565b5a0.patch"
cd "$workspace"
CMAKE_BUILD_PARALLEL_LEVEL=1 MAKEFLAGS=-j1 colcon build --merge-install \
  --packages-select mavros --packages-ignore libmavconn mavros_msgs \
  --allow-overriding mavros --executor sequential \
  --cmake-args -DCMAKE_BUILD_TYPE=RelWithDebInfo \
  '-DCMAKE_CXX_FLAGS_RELWITHDEBINFO=-O1 -g0 -DNDEBUG' -DBUILD_TESTING=ON
# Generated by the successful build above.
# shellcheck source=/dev/null
source install/local_setup.bash
colcon test --merge-install --packages-select mavros --return-code-on-test-failure \
  --ctest-args -R '^mavros-router-(test|e2e)$' --output-on-failure --timeout 120
cat > PROVENANCE.txt <<'RECEIPT'
MAVROS tag: 2.16.0
Base commit: 5c68b905ab30de6ce630822dc46c33467e8f23ea
Backports, in order:
a974025818cd6101a633c8c059c1a0155132d588
2b788a04e69e0aaaef78b9175f816dfcc565b5a0
Only mavros is rebuilt. libmavconn and mavros_msgs remain the ROS 2 Lyrical underlay.
RECEIPT
printf 'Overlay built. Explicitly select it with: source %q/install/local_setup.bash\n' "$workspace"
